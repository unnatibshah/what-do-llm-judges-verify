"""The exact prompt each ladder rung sends, rendered for one dev item, with sha256s (PREREGISTRATION_v3 appendix A).

No model is called: the LLM call is replaced by a stub that records the prompt. Dev split only. The test run's
per-row ``prompt_sha256`` is the record for test items; this file shows the templates the authors sign.

    python 30_code/scripts/render_prereg_prompts.py --out 20_method/PREREGISTRATION_v3_PROMPTS.md
"""

import argparse
import hashlib
from typing import Any

from suryabench.arms import verifier_probe as vp
from suryabench.arms import verify_reflect, verify_shared
from suryabench.eval.runner import BenchmarkRunConfig, BenchmarkRunner
from suryabench.paths import CODE_DIR, corpus_dir, resolve

SOURCES = ["src/suryabench/arms/verify_shared.py", "src/suryabench/arms/verify_independent.py",
           "src/suryabench/arms/verifier_probe.py"]
ITEMS = {"S-both": "SB-8dc1cbde#S-both#fault", "S-swap": "SB-8dc1cbde#S-swap#fault"}  # RJ-C3-002#cl-6.1, linked
LADDER = [("R0", "validity-metaoff", "S-swap"), ("R1", "validity", "S-swap"), ("R2", "validity", "S-both"),
          ("R3", "validity-amendquote", "S-both"), ("R4", "validity-regstatus", "S-both"),
          ("R4'", "validity-regstatus", "S-swap"), ("R0-cc", "validity-cc-metaoff", "S-swap"),
          ("R1-cc", "validity-cc", "S-swap"), ("R2-cc", "validity-cc", "S-both"),
          ("R4-drop25 (seed 0)", "validity-regstatus-drop25-s0", "S-both")]


def sha(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    runner = BenchmarkRunner(BenchmarkRunConfig(arm_id="arm3", cases_path=resolve("40_data/benchmark/dev_cases_v2.json"),
                                                corpus_dir=corpus_dir("r3"), metadata=True))
    items, _ = vp.build_items(runner.cases, runner.graph, runner.predicates, runner.retriever)
    by = {i.item_id: i for i in items}
    chosen = [by[k] for k in ITEMS.values()]
    ctx = vp.ProbeContext(
        cases={c.case_id: BenchmarkRunner._unlabelled(c) for c in runner.cases},
        texts=vp.evidence_texts(chosen, runner.graph, runner.retriever), retriever=runner.retriever,
        registries={**{n: runner._registry(n) for n in ("reg-oracle", "reg-real")},
                    **vp.damaged_registries(runner._registry("reg-real"))},
        labels={d.doc_id: "SRC-" + hashlib.sha256(f"probe|MODEL|{d.doc_id}".encode()).hexdigest()[:6].upper()
                for d in runner.corpus_manifest.documents})
    sent: list[str] = []

    def stub(prompt: str, **_: Any) -> tuple[dict[str, Any], int, int]:
        sent.append(prompt)
        return {"verdict": "PASS", "risk": 0.0, "findings": [], "reflection": "none"}, 0, 0

    verify_shared.call_llm_json = stub  # type: ignore[assignment]
    verify_reflect.call_llm_json = stub  # type: ignore[assignment]
    out = ["# PREREGISTRATION_v3, appendix A: the prompts", "",
           "Generated by `30_code/scripts/render_prereg_prompts.py` (no model called). Each block is the exact text one",
           "rung sends for one dev fault item (planted clause `RJ-C3-002#cl-6.1`). Metadata-off source labels are",
           "per model in the run (`SRC-` + 6 hex of sha256(`probe|<model>|<doc id>`)); here `MODEL` stands in. Test",
           "items use the same templates; their exact prompts are hashed per row (`prompt_sha256`) in every block.", "",
           "## Template sources", "", "| file | sha256 |", "|---|---|"]
    out += [f"| `30_code/{s}` | `{sha((CODE_DIR / s).read_text(encoding='utf-8'))}` |" for s in SOURCES]
    out.append("")
    for rung, config, cond in LADDER:
        before = len(sent)
        vp.verify_item(by[ITEMS[cond]], config, "MODEL", ctx)
        prompt = "\n\n".join(sent[before:])
        out += [f"## {rung}: `{config}` on {cond}", "", f"sha256 `{sha(prompt)}`", "", "````text", prompt, "````", ""]
    out += ["## R5 and R5-damaged", "", "Deterministic registry lookup (`reg-real`, `reg-<damage>-s<seed>`): no prompt.", ""]
    resolve(args.out).write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {args.out}: {len(LADDER)} prompts")


if __name__ == "__main__":
    main()
