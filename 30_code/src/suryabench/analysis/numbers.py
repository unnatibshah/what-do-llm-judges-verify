r"""Generate ``numbers.tex``: one ``\newcommand`` per manuscript number (decision D16).

Spec JSON maps macro name (letters only, e.g. ``SensZeroZeroZeroFthree``) to either a path
string or ``{"path": ..., "fmt": ".1f", "scale": 100, "file": "50_analysis/results/x.json"}``;
``file`` (repo-relative, resolved by ``suryabench.paths``) reads that JSON instead of ``--results``. Paths are dotted; integer parts index
lists (``arms.0.sens``). A missing path raises KeyError; nothing is written.

    python -m suryabench.analysis.numbers --results X.json --spec spec.json --out numbers.tex
"""

import argparse
import json
import re
from pathlib import Path
from typing import Any

from suryabench.paths import resolve

_NAME = re.compile(r"^[A-Za-z]+$")
_ESC = (("\\", r"\textbackslash{}"), ("%", r"\%"), ("&", r"\&"), ("_", r"\_"), ("#", r"\#"))


def lookup(data: Any, path: str) -> Any:
    cur = data
    for part in path.split("."):
        try:
            cur = cur[int(part)] if isinstance(cur, list) else cur[part]
        except (KeyError, IndexError, ValueError, TypeError) as e:
            raise KeyError(f"path {path!r} not found at {part!r}") from e
    return cur


def _tex(s: str) -> str:
    for a, b in _ESC:
        s = s.replace(a, b)
    return s


def render_macros(results: dict[str, Any], spec: dict[str, Any]) -> str:
    lines = ["% Generated by suryabench.analysis.numbers; do not edit."]
    files: dict[str, Any] = {}
    for name, item in spec.items():
        if not _NAME.match(name):
            raise ValueError(f"macro name {name!r} must contain letters only")
        src = results
        if isinstance(item, str):
            path, fmt, scale = item, "", 1.0
        else:
            path, fmt, scale = item["path"], item.get("fmt", ""), item.get("scale", 1.0)
            if "file" in item:
                f = item["file"]
                if f not in files:
                    files[f] = json.loads(resolve(f).read_text(encoding="utf-8"))
                src = files[f]
        val = lookup(src, path)
        if val is None or isinstance(val, dict | list):
            raise ValueError(f"{name}: path {path!r} is not a scalar ({val!r})")
        if scale != 1.0 and isinstance(val, int | float) and not isinstance(val, bool):
            val = val * scale
        text = format(val, fmt) if fmt else str(val)
        lines.append(f"\\newcommand{{\\{name}}}{{{_tex(text)}}}")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", required=True)
    ap.add_argument("--spec", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    results = json.loads(Path(a.results).read_text(encoding="utf-8"))
    spec = json.loads(Path(a.spec).read_text(encoding="utf-8"))
    tex = render_macros(results, spec)
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(tex)


if __name__ == "__main__":
    main()
