"""Arm 0: hand-coded rule system, no LLM, no retrieval.

A maintained expert system: it reads only the application facsimiles (via the same case
reader Arm 2 uses) and applies the current rules, hand-encoded with the deterministic tools
and the current feasibility timeline. It never reads gold case facts or labels.

Because benchmark labels are generated by rule functions over the same regulations, Arm 0
is a reference ceiling for a correctly maintained rule system on well-formed facsimiles. It
cannot be misled by superseded documents because it retrieves none; its real-world weakness
(manual maintenance whenever a rule changes) is not what this benchmark measures.
"""

from typing import Any

from pydantic import BaseModel, ConfigDict, Field

from suryabench.applicability.schema import ApplicabilityPredicate
from suryabench.arms.tools.almm_lookup import check_almm_and_dcr
from suryabench.arms.tools.capacity_est import evaluate_dt_capacity
from suryabench.arms.tools.case_reader import ParsedCaseFacts, parse_case_facsimiles
from suryabench.arms.tools.subsidy_calc import calculate_cfa_subsidy
from suryabench.cases.schema import BenchmarkCase
from suryabench.core.enums import ExpectedDecision
from suryabench.graph.schema import SupersessionGraph

DEEMED_ACCEPTANCE_KW = 10.0  # MERC 2024 / RERC 2024 provisos
STUDY_WINDOW_DAYS = 15  # presumed feasible after this without an outcome
NET_METERING_LIMIT_KW = 1000.0  # MERC 2.1(j) (<1 MW), RERC order 07.02.2024 (<=1 MW)
GHS_RATE_INR, GHS_MAX_KW, GHS_KW_PER_HOUSE = 18000, 500.0, 3.0


class Arm0Output(BaseModel):
    """Structured output returned by Arm 0."""

    model_config = ConfigDict(extra="forbid")

    decision: ExpectedDecision
    abstention_reason: str | None = None
    blocking_stage: str | None = None
    root_cause: str | None = None
    next_action: str | None = None
    prohibited_actions: list[str] = Field(default_factory=list)
    computed: list[dict[str, Any]] = Field(default_factory=list)
    cited_rules: list[str] = Field(default_factory=list)


def _reject(stage: str, cause: str, rules: list[str], computed: dict[str, Any] | None = None) -> Arm0Output:
    return Arm0Output(decision=ExpectedDecision.ANSWER, blocking_stage=stage, root_cause=cause,
                      next_action="Reject at the blocking stage and notify the applicant",
                      computed=[computed] if computed else [], cited_rules=rules)


def _approve(rules: list[str], computed: dict[str, Any] | None = None) -> Arm0Output:
    return Arm0Output(decision=ExpectedDecision.ANSWER, next_action="Proceed to the next stage",
                      computed=[computed] if computed else [], cited_rules=rules)


class Arm0DecisionTree:
    """Deterministic evaluator over parsed facsimiles (current rules only)."""

    def __init__(
        self,
        graph: SupersessionGraph | None = None,
        predicates: list[ApplicabilityPredicate] | None = None,
    ) -> None:
        self.graph = graph
        self.predicates = predicates or []

    def evaluate_case(self, case: BenchmarkCase) -> Arm0Output:
        """Evaluate one case from its facsimiles."""
        p = parse_case_facsimiles(case.inputs)
        if p.missing_fields:
            return Arm0Output(
                decision=ExpectedDecision.ABSTAIN,
                abstention_reason=f"F9: required information missing ({', '.join(p.missing_fields)})",
                prohibited_actions=["decide_without_required_information"],
            )
        stage = (p.application_stage or "").lower()
        if "equipment" in stage:
            return self._equipment(p)
        if "subsidy" in stage:
            return self._subsidy(p)
        if stage == "technical feasibility":
            return self._feasibility(p)
        return self._interconnection(p)

    # --- families -------------------------------------------------------------------
    def _equipment(self, p: ParsedCaseFacts) -> Arm0Output:
        res = check_almm_and_dcr(module_make=p.module_make, dcr_claimed=bool(p.dcr_compliant),
                                 case_date=p.case_date or "2024-06-15", subsidy_claimed=True)
        rules = ["IN-C2-002#cl-1" if (p.case_date or "") >= "2024-04-01" else "IN-C2-003#cl-1", "IN-C1-001#cl-5.1m"]
        if res.is_compliant:
            return _approve(rules)
        cause = "non_almm_modules" if not res.almm_enlisted and (p.case_date or "") >= "2024-04-01" \
            else "non_dcr_modules_for_cfa"
        return _reject("equipment_verification", cause, rules)

    def _subsidy(self, p: ParsedCaseFacts) -> Arm0Output:
        kw = p.proposed_capacity_kw or 0.0
        if not p.dcr_compliant:
            return _reject("equipment_verification", "non_dcr_modules_for_cfa", ["IN-C1-001#cl-5.1m"])
        if p.households:
            rule = "IN-C1-001#cl-4.gh"
            entitled = int(GHS_RATE_INR * min(kw, GHS_MAX_KW, GHS_KW_PER_HOUSE * p.households))
        else:
            rule = "IN-C1-001#cl-4.1"
            entitled = int(calculate_cfa_subsidy(proposed_capacity_kw=kw, consumer_category="residential",
                                                 dcr_compliant=True).subsidy_amount_inr)
        computed = {"subsidy_amount_inr": entitled, "claimed_cfa_inr": p.cfa_claim_inr}
        if p.cfa_claim_inr is not None and p.cfa_claim_inr > entitled:
            return _reject("subsidy_approval", "cfa_claim_exceeds_entitlement", [rule], computed)
        return _approve([rule], computed)

    def _feasibility(self, p: ParsedCaseFacts) -> Arm0Output:
        state = p.state or "MH"
        main = "MH-C3-002#cl-annex1-c" if state == "MH" else "RJ-C3-005#cl-8.8"
        load_rule = "MH-C3-001#cl-6.2" if state == "MH" else "RJ-C3-002#cl-7.2"
        kw = p.proposed_capacity_kw or 0.0
        if kw <= DEEMED_ACCEPTANCE_KW:
            return _approve([f"{main}-proviso"])
        if p.sanctioned_load_kw is not None and kw > p.sanctioned_load_kw:
            return _reject("technical_feasibility", "capacity_exceeds_sanctioned_load", [main, load_rule])
        if p.feasibility_outcome == "infeasible":
            return _reject("technical_feasibility", "feasibility_not_established", [main])
        if p.feasibility_outcome == "feasible" or (p.days_since_registration or 0) > STUDY_WINDOW_DAYS:
            return _approve([main])
        return _reject("technical_feasibility", "feasibility_not_established", [main])

    def _interconnection(self, p: ParsedCaseFacts) -> Arm0Output:
        state = p.state or "MH"
        kw = p.proposed_capacity_kw or 0.0
        ceiling = "MH-C3-001#cl-2.1j" if state == "MH" else "RJ-C3-004#cl-12"
        over = kw >= NET_METERING_LIMIT_KW if state == "MH" else kw > NET_METERING_LIMIT_KW
        if over:
            return _reject("metering_mode_selection", "net_metering_capacity_ceiling_exceeded", [ceiling])
        dt_rule = "MH-C3-001#cl-5.2" if state == "MH" else "RJ-C3-003#cl-2"
        load_rule = "MH-C3-001#cl-6.2" if state == "MH" else "RJ-C3-002#cl-7.2"
        rules = [load_rule]
        computed: dict[str, Any] = {}
        if p.own_transformer and state == "RJ":
            rules.insert(0, "RJ-C3-003#cl-2-proviso")  # HT consumer's own transformer: 80% limit n/a
        elif p.dt_capacity_kva is not None and p.cumulative_solar_kw is not None:
            dt = evaluate_dt_capacity(dt_capacity_kva=p.dt_capacity_kva, cumulative_solar_kw=p.cumulative_solar_kw,
                                      state=state)
            rules.insert(0, dt_rule)
            computed = {"dt_capacity_kva": dt.dt_capacity_kva, "cumulative_solar_kw": dt.cumulative_solar_kw,
                        "saturation_pct": dt.saturation_pct, "excess_kw": dt.excess_kw}
            if not dt.is_feasible:
                return _reject("technical_feasibility", "dt_hosting_limit_exceeded", rules, computed)
        if p.sanctioned_load_kw is not None and kw > p.sanctioned_load_kw:
            return _reject("technical_feasibility", "capacity_exceeds_sanctioned_load", rules, computed)
        return _approve(rules, computed)
